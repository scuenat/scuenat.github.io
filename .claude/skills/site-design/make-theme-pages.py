#!/usr/bin/env python3
"""Write one page per home-page theme: themes/<id>.qmd and fr/themes/<id>.qmd (site-design skill).

The themes (id, title, thesis, optional series link) are read from the `topics` listing in
index.qmd and fr/index.qmd, so they are defined in one place. Run it after adding, renaming or
re-describing a theme, then render. Pages are overwritten; do not edit them by hand.

Usage: python3 .claude/skills/site-design/make-theme-pages.py
"""
import os
import yaml

LANGS = {
    "en": {"index": "index.qmd", "dir": "themes", "posts": "../posts/*/index.qmd", "tpl": "../archive-list.ejs",
           "back": "← All themes", "series": "Also a series, to read in order:", "kinds": None,
           "intro": "Every post in this theme, in reading order, oldest first."},
    "fr": {"index": "fr/index.qmd", "dir": "fr/themes", "posts": "../posts/*/index.qmd", "tpl": "../../archive-list.ejs",
           "back": "← Tous les thèmes", "series": "C'est aussi une série, à lire dans l'ordre :",
           "kinds": {"essay": "Essai", "analysis": "Analyse", "note": "Note", "position": "Article de position", "overview": "Panorama"},
           "intro": "Tous les textes de ce thème, dans l'ordre de lecture, du plus ancien au plus récent."},
}


def front_matter(path):
    text = open(path, encoding="utf-8").read()
    return yaml.safe_load(text.split("\n---\n", 1)[0].lstrip("-\n"))


def series_title(link, lang):
    page = link.replace(".html", ".qmd")
    path = os.path.join("fr", page) if lang == "fr" else page
    return front_matter(path)["title"]


for lang, L in LANGS.items():
    meta = front_matter(L["index"])
    topics = next(x for x in meta["listing"] if x["id"] == "topics")["template-params"]["topics"]
    os.makedirs(L["dir"], exist_ok=True)
    for t in topics:
        params = {"theme": t["id"], "filters": False}
        if L["kinds"]:
            params["kinds"] = L["kinds"]
        fm = {
            "title": t["title"],
            "description": t["thesis"],
            "listing": [{
                "id": "posts",
                "contents": L["posts"],
                "sort": "date asc",
                "template": L["tpl"],
                "template-params": params,
                "fields": ["image", "date", "title", "subtitle", "description", "categories", "reading-time", "kind", "topics"],
            }],
            "page-layout": "full",
            "toc": False,
        }
        body = [f"<!-- Generated by .claude/skills/site-design/make-theme-pages.py from {L['index']}; do not edit. -->", "",
                f"[{L['back']}](../index.qmd#topics){{.theme-back}}", "", L["intro"]]
        if t.get("link"):
            body += ["", f"{L['series']} [{series_title(t['link'], lang)}](../{t['link'].replace('.html', '.qmd')})."]
        body += ["", "::: {#posts}", ":::", ""]
        out = os.path.join(L["dir"], t["id"] + ".qmd")
        with open(out, "w", encoding="utf-8") as f:
            f.write("---\n" + yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=1000) + "---\n\n" + "\n".join(body))
        print("wrote", out)
