import json, numpy as np, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

r = json.load(open("mnist_results.json")); L = np.array(r["Ls"]); sel = L <= 12
S, INK, INK2, MUTED, BLUE, ORANGE = "#fcfcfb", "#0b0b0b", "#52514e", "#a3a29e", "#2a78d6", "#eb6834"
ab, bm, bc = [], [], []
for p in r["points"]:
    ab.append(p["abar"])
    bm.append(np.polyfit(np.log(L[sel]), np.log(np.array(p["I_mix"])[sel]), 1)[0])
    bc.append(np.polyfit(np.log(L[sel]), np.log(np.array(p["I_ctl"])[sel]), 1)[0])

fig = plt.figure(figsize=(7.4, 4.3), dpi=200, facecolor=S)
gs = fig.add_gridspec(3, 7, width_ratios=[1, 1, 1, 0.9, 2.2, 2.2, 2.2], wspace=0.08, hspace=0.08)
smp = np.array(r["samples"])
for i in range(9):
    a = fig.add_subplot(gs[i // 3, i % 3])
    a.imshow(np.clip(smp[i], -1, 1).reshape(28, 28), cmap="Greys_r", vmin=-1, vmax=1); a.axis("off")
fig.text(0.03, 0.94, "Generated by the learned model", color=INK, fontsize=9)

ax = fig.add_subplot(gs[:, 4:]); ax.set_facecolor(S)
ax.axhline(1, color=MUTED, lw=1, ls="--", zorder=1)
ax.text(0.98, 0.985, "area law (β = 1)", ha="right", va="top", color=INK2, fontsize=8,
        transform=ax.get_yaxis_transform())
ax.plot(ab, bc, color=ORANGE, lw=2, ls=(0, (4, 2)), marker="s", ms=4.5, mec=S, mew=1.2,
        label="Gaussian control (same covariance)", zorder=3)
ax.plot(ab, bm, color=BLUE, lw=2, marker="o", ms=5, mec=S, mew=1.2,
        label="Learned MNIST model", zorder=4)
ax.annotate("noisy phase: extra,\nbulk-like information", (0.1, bm[1]), xytext=(4, 14),
            textcoords="offset points", color=INK, fontsize=8)
ax.annotate(f"finished digits: β = {bm[-1]:.2f}", (0.99, bm[-1]), xytext=(-30, -17), va="center",
            textcoords="offset points", ha="right", color=INK, fontsize=8)
ax.set_xscale("log"); ax.set_ylim(0.9, 1.6)
ax.set_xlabel("Signal fraction ᾱ (log scale; noise → finished image)", color=INK2, fontsize=9)
ax.set_ylabel("Scaling exponent β  (regions L = 2–12 px)", color=INK2, fontsize=9)
ax.set_title("Real digits converge to an area law", loc="left", color=INK, fontsize=10, pad=8)
ax.legend(loc="lower left", frameon=False, fontsize=7.5, labelcolor=INK2)
for s in ["top", "right"]: ax.spines[s].set_visible(False)
for s in ["left", "bottom"]: ax.spines[s].set_color(MUTED)
ax.tick_params(colors=INK2, labelsize=8, which="both")
ax.grid(axis="y", color="#e6e5e1", lw=0.6, zorder=0)
fig.subplots_adjust(left=0.03, right=0.98, top=0.88, bottom=0.14)
fig.savefig("mnist_beta.png", facecolor=S)
